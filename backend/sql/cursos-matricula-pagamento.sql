-- Matrícula e pagamento de cursos.
--
-- 1) O curso ganha as informações da tela de detalhes: nível, se emite
--    certificado, o que o aluno vai aprender, as skills desenvolvidas e a
--    carga horária de cada módulo.
-- 2) Matrícula: o candidato PCD se inscreve no curso. Curso gratuito já
--    nasce ATIVA; curso pago fica PENDENTE até o pagamento ser aprovado.
-- 3) Pagamento: cada tentativa (Pix ou cartão) feita pelo Mercado Pago. O
--    número do cartão NUNCA chega aqui — o navegador manda os dados direto
--    pro Mercado Pago e só recebemos um token; guardamos só a bandeira e os
--    4 últimos dígitos, pra mostrar no recibo.
-- 4) Avaliação: nota de 1 a 5 (e comentário opcional) de quem está matriculado.

USE `conecta+`;

ALTER TABLE TBLCDSCURSO0
  ADD COLUMN NIVEL ENUM('INICIANTE','INTERMEDIARIO','AVANCADO') NULL,
  ADD COLUMN CERTIFICADO TINYINT(1) NOT NULL DEFAULT 0;

ALTER TABLE TBLCDSCURSOMOD0
  ADD COLUMN CARGAHORARIA INT NULL;

-- Listas de itens do curso, no mesmo padrão das listas da vaga.
CREATE TABLE IF NOT EXISTS TBLCDSCURSOAPR0 (
  IDAPRENDIZADO INT NOT NULL AUTO_INCREMENT,
  IDCURSO INT NOT NULL,
  DESCRICAO VARCHAR(255) NOT NULL,
  PRIMARY KEY (IDAPRENDIZADO),
  CONSTRAINT FK_CURSOAPR_CURSO FOREIGN KEY (IDCURSO) REFERENCES TBLCDSCURSO0 (IDCURSO) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS TBLCDSCURSOSKILL0 (
  IDSKILL INT NOT NULL AUTO_INCREMENT,
  IDCURSO INT NOT NULL,
  DESCRICAO VARCHAR(60) NOT NULL,
  PRIMARY KEY (IDSKILL),
  CONSTRAINT FK_CURSOSKILL_CURSO FOREIGN KEY (IDCURSO) REFERENCES TBLCDSCURSO0 (IDCURSO) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS TBLCDSMATR0 (
  IDMATRICULA INT NOT NULL AUTO_INCREMENT,
  IDCURSO INT NOT NULL,
  IDPCD INT NOT NULL,
  -- Preço do curso no momento da matrícula: se a empresa mudar o preço
  -- depois, quem já começou a pagar continua pagando o valor combinado.
  VALOR DECIMAL(10,2) NOT NULL DEFAULT 0,
  OBSACESSIBILIDADE VARCHAR(500) NULL,
  STATUSMATRICULA ENUM('PENDENTE','ATIVA','CANCELADA') NOT NULL DEFAULT 'PENDENTE',
  DTCAD DATETIME DEFAULT CURRENT_TIMESTAMP,
  DTATIVACAO DATETIME NULL,
  PRIMARY KEY (IDMATRICULA),
  CONSTRAINT FK_MATR_CURSO FOREIGN KEY (IDCURSO) REFERENCES TBLCDSCURSO0 (IDCURSO) ON DELETE CASCADE,
  CONSTRAINT FK_MATR_PCD FOREIGN KEY (IDPCD) REFERENCES TBLCDSUSR0 (IDPCD) ON DELETE CASCADE,
  CONSTRAINT UQ_MATRICULA UNIQUE (IDCURSO, IDPCD)
);

-- Necessidades de acessibilidade marcadas na matrícula (uma linha por item).
CREATE TABLE IF NOT EXISTS TBLCDSMATRNEC0 (
  IDNECESSIDADE INT NOT NULL AUTO_INCREMENT,
  IDMATRICULA INT NOT NULL,
  DESCRICAO VARCHAR(100) NOT NULL,
  PRIMARY KEY (IDNECESSIDADE),
  CONSTRAINT FK_MATRNEC_MATRICULA FOREIGN KEY (IDMATRICULA) REFERENCES TBLCDSMATR0 (IDMATRICULA) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS TBLCDSPAG0 (
  IDPAGAMENTO INT NOT NULL AUTO_INCREMENT,
  IDMATRICULA INT NOT NULL,
  -- Id do pagamento no Mercado Pago (é por ele que o webhook avisa mudanças).
  IDEXTERNO VARCHAR(40) NULL,
  METODO ENUM('PIX','CARTAO') NOT NULL,
  VALOR DECIMAL(10,2) NOT NULL,
  PARCELAS INT NOT NULL DEFAULT 1,
  STATUSPAGAMENTO ENUM('PENDENTE','APROVADO','RECUSADO','CANCELADO','ESTORNADO') NOT NULL DEFAULT 'PENDENTE',
  -- Motivo detalhado devolvido pelo Mercado Pago (ex.: cc_rejected_insufficient_amount).
  DETALHESTATUS VARCHAR(80) NULL,
  PIXCOPIACOLA TEXT NULL,
  PIXQRCODE MEDIUMTEXT NULL,
  PIXEXPIRACAO DATETIME NULL,
  CARTAOBANDEIRA VARCHAR(30) NULL,
  CARTAOFINAL CHAR(4) NULL,
  DTCAD DATETIME DEFAULT CURRENT_TIMESTAMP,
  DTATUALIZACAO DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (IDPAGAMENTO),
  UNIQUE KEY UQ_PAGAMENTO_EXTERNO (IDEXTERNO),
  CONSTRAINT FK_PAG_MATRICULA FOREIGN KEY (IDMATRICULA) REFERENCES TBLCDSMATR0 (IDMATRICULA) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS TBLCDSCURSOAVAL0 (
  IDAVALIACAO INT NOT NULL AUTO_INCREMENT,
  IDCURSO INT NOT NULL,
  IDPCD INT NOT NULL,
  NOTA TINYINT NOT NULL,
  COMENTARIO VARCHAR(500) NULL,
  DTCAD DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (IDAVALIACAO),
  CONSTRAINT FK_AVAL_CURSO FOREIGN KEY (IDCURSO) REFERENCES TBLCDSCURSO0 (IDCURSO) ON DELETE CASCADE,
  CONSTRAINT FK_AVAL_PCD FOREIGN KEY (IDPCD) REFERENCES TBLCDSUSR0 (IDPCD) ON DELETE CASCADE,
  CONSTRAINT UQ_AVALIACAO UNIQUE (IDCURSO, IDPCD),
  CONSTRAINT CK_AVAL_NOTA CHECK (NOTA BETWEEN 1 AND 5)
);
