-- Ambiente administrativo da equipe Conecta+: validação dos cadastros de
-- empresa. Só a equipe muda o status de uma empresa (a própria empresa não
-- consegue mais se aprovar pela API).

USE `conecta+`;

-- Membros da equipe. Entram com e-mail e senha (hash scrypt, igual às outras
-- contas). O primeiro é criado pelo terminal: npm run criar-admin
CREATE TABLE IF NOT EXISTS TBLCDSADM0 (
  IDADMIN INT NOT NULL AUTO_INCREMENT,
  NOME VARCHAR(150) NOT NULL,
  EMAIL VARCHAR(150) NOT NULL,
  SENHA VARCHAR(255) NOT NULL,
  STATUSADM ENUM('ATIVO','INATIVO') NOT NULL DEFAULT 'ATIVO',
  DTCAD DATETIME DEFAULT CURRENT_TIMESTAMP,
  DTULTIMOACESSO DATETIME NULL,
  PRIMARY KEY (IDADMIN),
  CONSTRAINT UQ_ADMIN_EMAIL UNIQUE (EMAIL)
);

-- Empresa recusada: não consegue entrar e vê o motivo ao tentar.
ALTER TABLE TBLCDSEMP0
  MODIFY COLUMN STATUSEMP ENUM('ATIVA','INATIVA','PENDENTE','RECUSADA') DEFAULT 'PENDENTE';

-- Histórico das decisões da equipe: quem aprovou/recusou/inativou, quando e por quê.
CREATE TABLE IF NOT EXISTS TBLCDSEMPHIST0 (
  IDHISTORICO INT NOT NULL AUTO_INCREMENT,
  IDEMPRESA INT NOT NULL,
  IDADMIN INT NULL,
  STATUSANTERIOR ENUM('ATIVA','INATIVA','PENDENTE','RECUSADA') NULL,
  STATUSNOVO ENUM('ATIVA','INATIVA','PENDENTE','RECUSADA') NOT NULL,
  MOTIVO VARCHAR(500) NULL,
  DTCAD DATETIME DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (IDHISTORICO),
  CONSTRAINT FK_EMPHIST_EMPRESA FOREIGN KEY (IDEMPRESA) REFERENCES TBLCDSEMP0 (IDEMPRESA) ON DELETE CASCADE,
  CONSTRAINT FK_EMPHIST_ADMIN FOREIGN KEY (IDADMIN) REFERENCES TBLCDSADM0 (IDADMIN) ON DELETE SET NULL
);

-- Preferências de acessibilidade também por membro da equipe.
ALTER TABLE TBLCDSPREFACS0
  DROP CHECK CK_PREFACS_DONO,
  ADD COLUMN IDADMIN INT NULL AFTER IDEMPRESA,
  ADD CONSTRAINT UQ_PREFACS_ADMIN UNIQUE (IDADMIN),
  ADD CONSTRAINT FK_PREFACS_ADMIN FOREIGN KEY (IDADMIN) REFERENCES TBLCDSADM0 (IDADMIN) ON DELETE CASCADE,
  ADD CONSTRAINT CK_PREFACS_DONO CHECK (
    (IDPCD IS NOT NULL) + (IDEMPRESA IS NOT NULL) + (IDADMIN IS NOT NULL) = 1
  );
